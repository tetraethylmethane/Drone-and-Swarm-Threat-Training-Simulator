import { lazy, Suspense, useCallback, useMemo, useState } from "react";
import { Link, useNavigate, useParams } from "react-router-dom";

import { Button } from "@/components/ui/button";
import { Dialog } from "@/components/ui/overlay";
import { KeyValues, Panel, PanelBody, PanelHeader } from "@/components/ui/panel";
import { Alert, Tag, toneForStatus } from "@/components/ui/status";
import { ErrorState, LoadingState } from "@/components/ui/states";
import { formatClock } from "@/lib/format";
import { CLASSIFICATION_LABELS, ENV_LABELS, label, STATUS_LABELS } from "@/lib/labels";
import { errorMessage } from "@/lib/useAsync";

import { DecisionPanel, EventLog, SensorPanel, TrackTable } from "./panels";
import { PlanView } from "./PlanView";
import { sortedTracks } from "./trackPicture";
import { useExercise } from "./useExercise";
import { CLASS_COLORS } from "./visual";

const SceneView = lazy(() => import("./SceneView").then((m) => ({ default: m.SceneView })));

function hasWebGL(): boolean {
  try {
    const c = document.createElement("canvas");
    return Boolean(c.getContext("webgl2") ?? c.getContext("webgl"));
  } catch {
    return false;
  }
}

export function ExercisePage() {
  const { sessionId = "" } = useParams();
  const navigate = useNavigate();
  const ex = useExercise(sessionId);
  const [selected, setSelected] = useState<Set<string>>(new Set());
  const [view, setView] = useState<"3d" | "plan">(() => (hasWebGL() ? "3d" : "plan"));
  const [confirmEnd, setConfirmEnd] = useState(false);
  const [opError, setOpError] = useState<string | null>(null);
  const tracks = useMemo(() => sortedTracks(ex.picture), [ex.picture]);

  const toggle = useCallback((id: string, additive: boolean) => {
    setSelected((prev) => {
      const next = new Set(additive ? prev : []);
      if (additive && prev.has(id)) next.delete(id);
      else next.add(id);
      return next;
    });
  }, []);

  const run = async (op: "start" | "pause" | "resume" | "complete") => {
    setOpError(null);
    try {
      const s = await ex.transition(op);
      if (s.status === "completed") navigate(`/sessions/${sessionId}/result`);
    } catch (err) {
      setOpError(errorMessage(err));
    }
  };

  if (ex.error && !ex.state)
    return <ErrorState error={ex.error} onRetry={ex.refresh} title="This exercise could not be opened" />;
  if (!ex.state) return <LoadingState label="Loading exercise" rows={6} />;
  const s = ex.state;
  const b = s.briefing;
  const running = s.status === "running";
  const finished = s.status === "completed" || s.status === "aborted";
  const env = b?.environment;

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-3 rounded-md border border-border bg-surface px-4 py-3">
        <div className="min-w-0">
          <p className="text-xs text-ink-subtle">
            Exercise · attempt {s.attempt_number} · difficulty {s.difficulty_level} · seed {s.seed}
          </p>
          <h1 className="truncate text-lg">{s.scenario.name}</h1>
        </div>
        <div className="flex flex-wrap items-center gap-4">
          <div className="text-right">
            <p className="text-2xs uppercase tracking-wide text-ink-subtle">Exercise time</p>
            <p className="tabular text-lg font-semibold" aria-live="off">
              {formatClock(ex.displayMs)}{" "}
              <span className="text-sm font-normal text-ink-subtle">/ {formatClock(s.duration_ms)}</span>
            </p>
          </div>
          <Tag tone={toneForStatus(s.status)}>{label(STATUS_LABELS, s.status)}</Tag>
          {s.status === "created" ? <Button onClick={() => run("start")}>Start exercise</Button> : null}
          {running && s.allow_pause ? (
            <Button variant="secondary" onClick={() => run("pause")}>
              Pause
            </Button>
          ) : null}
          {s.status === "paused" ? <Button onClick={() => run("resume")}>Resume</Button> : null}
          {running || s.status === "paused" ? (
            <Button variant="secondary" onClick={() => setConfirmEnd(true)}>
              Finish exercise
            </Button>
          ) : null}
          {finished ? (
            <Button asChild>
              <Link to={`/sessions/${sessionId}/result`}>View result</Link>
            </Button>
          ) : null}
        </div>
      </div>

      <Alert tone="info">
        Synthetic training data. Tracks and sensor readings are generated by the exercise and are not real
        measurements.
      </Alert>
      {ex.connection === "retrying" ? (
        <Alert tone="warning" title="Connection to the training server interrupted">
          Retrying automatically. If the interruption lasts more than a few seconds the exercise pauses itself
          and nothing already submitted is lost.
        </Alert>
      ) : null}
      {s.status === "paused" && s.pause_reason === "connection_lost" ? (
        <Alert tone="warning" title="Paused after a lost connection">
          The exercise clock stopped when the connection was lost. Resume when ready.
        </Alert>
      ) : null}
      {opError ? <Alert tone="danger">{opError}</Alert> : null}

      {s.status === "created" && b ? (
        <Panel>
          <PanelHeader
            title="Before you start"
            description="The clock starts when you select Start exercise."
          />
          <PanelBody className="grid gap-6 lg:grid-cols-2">
            <div>
              <p className="whitespace-pre-line text-sm leading-relaxed">{b.briefing}</p>
              <h3 className="mt-4">Objectives</h3>
              <ol className="mt-1 list-decimal space-y-1 pl-5 text-sm">
                {b.learning_objectives.map((o) => (
                  <li key={o.id}>{o.description}</li>
                ))}
              </ol>
            </div>
            {env ? (
              <KeyValues
                items={[
                  [
                    "Environment",
                    `${label(ENV_LABELS, env.terrain)}, ${label(ENV_LABELS, env.time_of_day)}, ${label(ENV_LABELS, env.weather)}`,
                  ],
                  ["Visibility", `${env.visibility_km} km`],
                  ["Duration", formatClock(b.duration_s * 1000)],
                  ["Pausing", b.allow_pause ? "Permitted" : "Not permitted"],
                ]}
              />
            ) : null}
          </PanelBody>
        </Panel>
      ) : null}

      <div className="grid gap-4 xl:grid-cols-[minmax(0,1fr)_380px]">
        <div className="min-w-0 space-y-4">
          <Panel>
            <PanelHeader
              title="Sensor picture"
              description="Colour shows your own classification. Rings every 1 km around the protected virtual site."
              actions={
                <div
                  className="flex rounded border border-border-strong p-0.5"
                  role="group"
                  aria-label="View mode"
                >
                  {(["3d", "plan"] as const).map((v) => (
                    <button
                      key={v}
                      type="button"
                      aria-pressed={view === v}
                      onClick={() => setView(v)}
                      className={`rounded px-2.5 py-1 text-xs ${view === v ? "bg-brand text-brand-ink" : "text-ink-muted hover:text-ink"}`}
                    >
                      {v === "3d" ? "3D view" : "Plan view"}
                    </button>
                  ))}
                </div>
              }
            />
            <div className="h-[420px] border-b border-border">
              {view === "3d" && env ? (
                <Suspense fallback={<LoadingState label="Loading 3D view" />}>
                  <SceneView
                    tracks={tracks}
                    environment={env}
                    visibilityKm={ex.picture.visibilityKm}
                    selected={selected}
                    onSelect={toggle}
                  />
                </Suspense>
              ) : (
                <PlanView
                  tracks={tracks}
                  selected={selected}
                  onSelect={toggle}
                  dark={env?.time_of_day === "night"}
                />
              )}
            </div>
            <div className="flex flex-wrap gap-x-4 gap-y-1 px-4 py-2 text-2xs text-ink-muted">
              {Object.entries(CLASS_COLORS).map(([k, c]) => (
                <span key={k} className="inline-flex items-center gap-1.5">
                  <span aria-hidden="true" className="h-2 w-2 rounded-full" style={{ background: c }} />
                  {k === "unclassified" ? "Not classified" : label(CLASSIFICATION_LABELS, k)}
                </span>
              ))}
            </div>
          </Panel>
          <Panel>
            <PanelHeader
              title={`Tracks (${tracks.length})`}
              description="R radar · O optical · RF radio frequency. Shift-click to select several."
            />
            <TrackTable tracks={tracks} selected={selected} onToggle={toggle} nowMs={ex.displayMs} />
          </Panel>
        </div>
        <div className="space-y-4">
          <Panel>
            <PanelHeader title="Decision" />
            <PanelBody>
              <DecisionPanel selected={[...selected].sort()} disabled={!running} onSubmit={ex.submit} />
              {!running && !finished ? (
                <p className="mt-3 text-xs text-ink-subtle">
                  Decisions can be submitted while the exercise is running.
                </p>
              ) : null}
            </PanelBody>
          </Panel>
          <Panel>
            <PanelHeader title="Simulated sensor status" />
            <SensorPanel picture={ex.picture} />
          </Panel>
          <Panel>
            <PanelHeader title="Exercise log" />
            <EventLog picture={ex.picture} />
          </Panel>
        </div>
      </div>

      <Dialog
        open={confirmEnd}
        onOpenChange={setConfirmEnd}
        title="Finish the exercise?"
        description="Your decisions are scored as soon as you finish. Tracks you have not classified count as missed."
        footer={
          <>
            <Button variant="secondary" onClick={() => setConfirmEnd(false)}>
              Keep going
            </Button>
            <Button
              onClick={async () => {
                setConfirmEnd(false);
                await run("complete");
              }}
            >
              Finish and score
            </Button>
          </>
        }
      />
    </div>
  );
}
